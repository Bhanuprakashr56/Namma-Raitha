export function t(key: keyof TranslationStrings | string, lang: Language): string {
  // Check comprehensive dictionary first for richer translations
  const phrase = getLocalizedPhrase(key as string, lang);
  if (phrase) return phrase;

  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  if ((dict as any)[key]) return (dict as any)[key];
  if ((TRANSLATIONS.en as any)[key]) return (TRANSLATIONS.en as any)[key];

  return String(key);
}

export function tr(keyOrText: string, lang: Language): string {
  return t(keyOrText, lang);
}

export function getCommodityName(name: string, lang: Language): string {
  return getLocalizedCommodity(name, lang);
}

