// Generic phrase translation function
export function getLocalizedPhrase(key: string, lang: Language): string | null {
  const entry = COMPREHENSIVE_UI[key];
  if (entry) {
    if (entry[lang]) {
      return entry[lang] as string;
    }
    if (entry.en) {
      return entry.en as string;
    }
  }
  return null;
}

// Translate commodity / crop produce by name
export function getLocalizedCommodity(name: string, lang: Language): string {
  if (lang === 'en' || !name) return name;
  for (const [key, translations] of Object.entries(COMMODITY_NAMES)) {
    if (name.toLowerCase().includes(key.toLowerCase())) {
      const trans = translations[lang];
      if (trans) return trans;
    }
  }
  return name;
}
